type Seed = {
  id: string;
  groupId: EmailTemplateGroupId;
  categoryId: string;
  eventId: string;
  name: string;
  kind?: EmailTemplateKind;
  isDefault?: boolean;
  audience?: string;
  subject: string;
  body: string;
  lastUpdatedBy?: string;
  lastUpdatedAt?: string;
};

function seed(item: Seed): EmailTemplateRecord {
  const at = item.lastUpdatedAt ?? '2026-04-08T11:20:00';
  const actor = item.lastUpdatedBy ?? 'Exxat One';
  return {
    id: item.id,
    groupId: item.groupId,
    categoryId: item.categoryId,
    eventId: item.eventId,
    name: item.name,
    kind: item.kind ?? 'standard',
    isDefault: item.isDefault ?? true,
    audience: item.audience,
    subject: item.subject,
    body: item.body,
    lastUpdatedBy: actor,
    lastUpdatedAt: at,
    history: [{ id: `${item.id}-created`, type: 'created', actor, at }],
  };
}

